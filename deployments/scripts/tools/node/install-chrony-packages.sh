#!/bin/bash
# ============================================================
# install-chrony-packages.sh —— 节点 chrony 离线装包(可选步骤)
#
# 设计边界(2026-11-19 用户口径):
#   · 装包与 NTP 同步**解耦** —— 本工具只安装 offline-files/os/packages/chrony
#     专用安装集, 不写 chrony.conf、不启停/配置 NTP 服务;
#     同步(权威/客户端配置 + 偏差校验)由 k8s_ntp(tools/node/setup-ntp.sh)负责.
#   · NTP 同步是**必选**步骤; 安装 OS 包是**可选**的: 默认假设节点黄金镜像
#     已预装 chrony. 需要 installer 装包时启用可选模块 chrony_pkgs
#     (cluster.conf CHRONY_PKGS_ENABLED=true / --steps chrony_pkgs).
#   · 幂等: 节点已有 chronyd + chronyc → 直接跳过(不上传、不装包).
#   · 安装集内 chrony 与 systemd-timesyncd 互斥: 复用 lib-common 的
#     install_debs_offline(预卸互斥 → 已装即跳 → 批量 dpkg → 逐包隔离).
#
# 用法: bash install-chrony-packages.sh [--ip <IP>]...
#   --ip 可多次; 不给 = cluster.conf NODES 全部节点(受 ONLY_HOSTS 过滤)
# 退出码: 0=全部目标节点 chronyd/chronyc 就绪; 1=有节点失败
# 数据源: <OFFLINE_FILES_ROOT>/os/packages/chrony/*.deb
# ============================================================
set -euo pipefail

# shellcheck source=lib-common.sh
source "$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/../../lib-common.sh"
load_config

DEB_DIR="${OFFLINE_FILES_ROOT:-${REPO_ROOT}/deployments/offline-files}/os/packages/chrony"
PKG_ROOT="$(dirname "${DEB_DIR}")"
if [ ! -d "${DEB_DIR}" ]; then
    err "未找到 chrony 专用安装集目录: ${DEB_DIR}"
    err "  本步骤是可选的(默认假设节点镜像已预装 chrony); 若需 installer 装包, 请把"
    err "  chrony 及依赖闭包 .deb 放入该目录, 或关闭本步骤(CHRONY_PKGS_ENABLED=false)"
    exit 1
fi
shopt -s nullglob
_chk_debs=("${DEB_DIR}"/*.deb)
shopt -u nullglob
if [ "${#_chk_debs[@]}" -eq 0 ]; then
    err "chrony 安装集为空: ${DEB_DIR}(需要 chrony 及其依赖闭包 .deb)"
    exit 1
fi
unset _chk_debs
say "chrony 离线安装集: ${DEB_DIR}($(find "${DEB_DIR}" -maxdepth 1 -name '*.deb' | wc -l) 个 deb)"

# ---------------- 目标节点 --ip 显式优先; 否则 NODES 全部(ONLY_HOSTS 过滤) ----------------
IPS=()
while [ $# -gt 0 ]; do
    case "$1" in
        --ip) IPS+=("${2:?--ip 需要地址}"); shift 2 ;;
        *) err "未知参数: $1"; exit 1 ;;
    esac
done
NODE_ENTRIES=()
for line in "${NODES[@]:-}"; do
    [ -z "${line}" ] && continue
    node_parse "${line}"
    [ -n "${NODE_IP}" ] && [ -n "${NODE_USER}" ] || continue
    node_matches "${NODE_HOSTNAME}" || continue
    if [ "${#IPS[@]}" -gt 0 ]; then
        _hit=0
        for _ip in "${IPS[@]}"; do [ "${_ip}" = "${NODE_IP}" ] && { _hit=1; break; }; done
        [ "${_hit}" = "1" ] || continue
    fi
    NODE_ENTRIES+=("${NODE_IP}:${NODE_USER}:${NODE_PW}:${NODE_HOSTNAME}")
done
[ "${#NODE_ENTRIES[@]}" -gt 0 ] || { err "没有目标节点(cluster.conf NODES 为空或 --ip 不在 NODES 中)"; exit 1; }

# ---------------- SSH 助手(与 setup-ntp.sh 同口径: 密钥优先, 密码回退) ----------------
SSH_KEY="${SSH_KEY_DIR:-${REAL_HOME:-$HOME}/.ssh}/${SSH_KEY_NAME:-cubestack_k8s}"
SSH_OPTS=(-i "${SSH_KEY}" -o StrictHostKeyChecking=no -o UserKnownHostsFile=/dev/null -o ConnectTimeout=8)

node_cmd() {   # <ip> <user> <pw> <remote cmd...>
    local ip="$1" u="$2" pw="$3"; shift 3
    local full
    if [ "${u}" = "root" ]; then
        full="$*"
    else
        full="sudo $*"
    fi
    if ssh "${SSH_OPTS[@]}" -o BatchMode=yes "${u}@${ip}" "$full" 2>/dev/null; then return 0; fi
    [ -n "${pw}" ] || return 1
    if [ "${u}" = "root" ]; then
        SSHPASS="${pw}" sshpass -e ssh -o StrictHostKeyChecking=no -o UserKnownHostsFile=/dev/null \
            -o PreferredAuthentications=password -o PubkeyAuthentication=no -o ConnectTimeout=8 \
            "${u}@${ip}" "$*"
    else
        SSHPASS="${pw}" sshpass -e ssh -o StrictHostKeyChecking=no -o UserKnownHostsFile=/dev/null \
            -o PreferredAuthentications=password -o PubkeyAuthentication=no -o ConnectTimeout=8 \
            "${u}@${ip}" "echo '${pw}' | sudo -S -p '' $*"
    fi
}

node_scp() {   # <local> <ip> <user> <pw> <remote_path>
    local l="$1" ip="$2" u="$3" pw="$4" r="$5"
    node_cmd "${ip}" "${u}" "${pw}" "rm -f '${r}'" >/dev/null 2>&1 || true
    if scp "${SSH_OPTS[@]}" -o BatchMode=yes -o ConnectTimeout=8 "$l" "${u}@${ip}:${r}" 2>/dev/null; then return 0; fi
    [ -n "${pw}" ] || return 1
    SSHPASS="${pw}" sshpass -e scp -o StrictHostKeyChecking=no -o UserKnownHostsFile=/dev/null \
        -o PreferredAuthentications=password -o PubkeyAuthentication=no -o ConnectTimeout=8 "$l" "${u}@${ip}:${r}"
}

# ---------------- 远端安装脚本(只装包; 不写配置/不启停服务) ----------------
REMOTE_SCRIPT="/tmp/cubestack-chrony-install.sh"
REMOTE_DEB_DIR="/tmp/cubestack-chrony-debs"
SCRIPT_TMP="$(mktemp)"
STAGE_TMP="$(mktemp -d)"
TAR_TMP="$(mktemp -t cubestack-chrony-debs.XXXXXX.tar.gz)"
trap 'rm -f "${SCRIPT_TMP}" "${TAR_TMP}"; rm -rf "${STAGE_TMP}"' EXIT

{
    deb_install_remote_lib
    cat <<'EOF'
#!/bin/bash
# Auto-generated by install-chrony-packages.sh — 只装包, 不改 NTP 配置(do not edit)
set -u
D=/tmp/cubestack-chrony-debs
shopt -s nullglob
_debs=("${D}"/*.deb)
if [ "${#_debs[@]}" -eq 0 ]; then
    echo "NO-DEBS: ${D}"
    exit 1
fi
if ! install_debs_offline "${D}" chrony; then
    echo "CHRONY-INSTALL-FAILED: install_debs_offline 返回非零(明细: /tmp/cubestack-deb-install.log)"
    tail -20 /tmp/cubestack-deb-install.log 2>/dev/null || true
    exit 1
fi
if assert_pkgs_ready chrony && command -v chronyd >/dev/null 2>&1 && command -v chronyc >/dev/null 2>&1; then
    echo "CHRONY-READY:$(dpkg-query -W -f='${Version}' chrony 2>/dev/null || true)"
else
    echo "CHRONY-INSTALL-FAILED: chrony 未处于 install ok installed(或缺少 chronyd/chronyc)"
    tail -20 /tmp/cubestack-deb-install.log 2>/dev/null || true
    exit 1
fi
EOF
} > "${SCRIPT_TMP}"

# 预卸 systemd-timesyncd 前必须能恢复它: 把顶层 os/packages 里的
# time-daemon deb 一并放进 tar 的 rollback/ 子目录(远端 install_debs_offline
# 只装顶层 *.deb, 不会把回滚包误当待装包).
cp -a "${DEB_DIR}/." "${STAGE_TMP}/"
mkdir -p "${STAGE_TMP}/rollback"
_rb_n=0
for _rb in "${PKG_ROOT}"/systemd-timesyncd_*.deb "${PKG_ROOT}"/openntpd_*.deb "${PKG_ROOT}"/ntp_*.deb; do
    [ -f "${_rb}" ] || continue
    cp -a "${_rb}" "${STAGE_TMP}/rollback/" && _rb_n=$((_rb_n + 1))
done
say "  时间同步回滚包: ${_rb_n} 个(rollback/, 仅替换失败时恢复)"
[ "${_rb_n}" -gt 0 ] || warn "  未找到 time-daemon 回滚包; 节点若仍用 systemd-timesyncd, 远端将拒绝预卸(需把 timesyncd deb 放入 os/packages)"
unset _rb_n _rb
tar -C "${STAGE_TMP}" -czf "${TAR_TMP}" .

# ---------------- 逐节点: 已装跳过 → 推送安装集 → 远端装包 ----------------
FAIL=0
for e in "${NODE_ENTRIES[@]}"; do
    ip="${e%%:*}"; rest="${e#*:}"
    u="${rest%%:*}"; rest="${rest#*:}"
    pw="${rest%%:*}"; rest="${rest#*:}"
    hn="${rest%%:*}"

    # SSH/sudo 前置: 区分"节点不可达"与"节点缺 chrony", 避免把 SSH 失败误报成装包失败
    if ! node_cmd "${ip}" "${u}" "${pw}" "true" >/dev/null 2>&1; then
        warn "  ${hn}(${ip}) SSH/sudo 不可用(user=${u}), 跳过装包"
        FAIL=1
        continue
    fi
    if node_cmd "${ip}" "${u}" "${pw}" \
        "bash -c \"dpkg-query -W -f='\${Status}' chrony 2>/dev/null | grep -q 'install ok installed' && command -v chronyd >/dev/null 2>&1 && command -v chronyc >/dev/null 2>&1\"" >/dev/null 2>&1; then
        ok "  ${hn}(${ip}) 已安装 chrony(install ok installed), 跳过"
        continue
    fi

    say "  ${hn}(${ip}) 缺 chrony → 离线安装 ..."
    if ! node_scp "${TAR_TMP}" "${ip}" "${u}" "${pw}" "/tmp/cubestack-chrony-debs.tar.gz"; then
        warn "  ${hn}(${ip}) 上传 chrony 安装集失败"
        FAIL=1
        continue
    fi
    if ! node_cmd "${ip}" "${u}" "${pw}" \
        "rm -rf ${REMOTE_DEB_DIR} && mkdir -p ${REMOTE_DEB_DIR} && tar -xzf /tmp/cubestack-chrony-debs.tar.gz -C ${REMOTE_DEB_DIR} && rm -f /tmp/cubestack-chrony-debs.tar.gz" >/dev/null 2>&1; then
        warn "  ${hn}(${ip}) 解包 chrony 安装集失败"
        FAIL=1
        continue
    fi
    if ! node_scp "${SCRIPT_TMP}" "${ip}" "${u}" "${pw}" "${REMOTE_SCRIPT}"; then
        warn "  ${hn}(${ip}) 上传安装脚本失败"
        FAIL=1
        continue
    fi

    _rout="$(node_cmd "${ip}" "${u}" "${pw}" "bash ${REMOTE_SCRIPT}" 2>&1)" && _rok=1 || _rok=0
    if [ "${_rok}" = "1" ] && printf '%s' "${_rout}" | grep -q 'CHRONY-READY'; then
        ok "  ${hn}(${ip}) $(printf '%s' "${_rout}" | grep 'CHRONY-READY' | tail -1)"
    else
        warn "  ${hn}(${ip}) chrony 装包失败: $(printf '%s' "${_rout}" | tail -3 | tr '\n' ' ')"
        FAIL=1
    fi
    unset _rout _rok
    node_cmd "${ip}" "${u}" "${pw}" "rm -f ${REMOTE_SCRIPT}; rm -rf ${REMOTE_DEB_DIR}" >/dev/null 2>&1 || true
done

if [ "${FAIL}" -ne 0 ]; then
    err "有节点 chrony 装包失败; 修复后重跑 --steps chrony_pkgs"
    exit 1
fi
ok "全部目标节点 chrony 已就绪(仅装包; NTP 配置/同步由 k8s_ntp 负责)"
